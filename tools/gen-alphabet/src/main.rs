//! Generates the import alphabet table from the Unicode Character Database.
//!
//! Usage: `gen-alphabet <ucd-dir> <unicode-version> > src/import/alphabet/table.rs`
//!
//! `<ucd-dir>` must contain `UnicodeData.txt`, `EastAsianWidth.txt`,
//! `DerivedCoreProperties.txt`, `PropList.txt` and `DerivedBidiClass.txt`
//! (from `extracted/`) of the given version. See README.md.
//!
//! The alphabet holds every character the schema's `char` pattern
//! `^[^.=\s\p{Cc}\p{Cf}\p{M}]$` accepts, in two tiers:
//!
//! - tier 1: assigned, not private use, not East Asian Wide/Fullwidth, not
//!   right-to-left (bidi R/AL), not default-ignorable, not a noncharacter;
//!   ordered as the fixed ASCII prefix, then by code point;
//! - tier 2: every other accepted character, by code point.

use std::fmt::Write as _;
use std::path::Path;
use std::{env, fs, process};

const MAX: u32 = 0x10FFFF;

/// The fixed start of tier 1, in order.
const ASCII_PREFIX: &str = concat!(
    "abcdefghijklmnopqrstuvwxyz",
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
    "0123456789",
    "!#$%&()*+,-/:;<>?@[]^_{|}~",
    "\"'\\`",
);

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: gen-alphabet <ucd-dir> <unicode-version>");
        process::exit(2);
    }
    let dir = Path::new(&args[1]);
    let version = &args[2];
    let read = |name: &str| {
        let text = fs::read_to_string(dir.join(name)).unwrap_or_else(|e| {
            eprintln!("{}: {e}", dir.join(name).display());
            process::exit(2);
        });
        let header = text.lines().next().unwrap_or_default();
        let is_unicode_data = name == "UnicodeData.txt";
        if !is_unicode_data && !header.contains(&format!("-{version}.txt")) {
            eprintln!("{name}: header {header:?} is not version {version}");
            process::exit(2);
        }
        text
    };

    let unicode_data = read("UnicodeData.txt");
    let gc = general_categories(&unicode_data);
    let eaw = property_values(&read("EastAsianWidth.txt"));
    let bidi = property_values(&read("DerivedBidiClass.txt"));
    let core = read("DerivedCoreProperties.txt");
    let props = read("PropList.txt");
    let ignorable = binary_property(&core, "Default_Ignorable_Code_Point");
    let nonchar = binary_property(&props, "Noncharacter_Code_Point");
    let white = binary_property(&props, "White_Space");

    let accepted = |cp: u32| -> bool {
        if (0xD800..=0xDFFF).contains(&cp) || cp == '.' as u32 || cp == '=' as u32 {
            return false;
        }
        let cat = gc[cp as usize];
        !white[cp as usize] && cat != "Cc" && cat != "Cf" && !cat.starts_with('M')
    };
    let tier1 = |cp: u32| -> bool {
        let cat = gc[cp as usize];
        !matches!(cat, "Cn" | "Co" | "Cs")
            && !matches!(eaw[cp as usize].as_str(), "W" | "F")
            && !matches!(bidi[cp as usize].as_str(), "R" | "AL" | "Right_To_Left" | "Arabic_Letter")
            && !ignorable[cp as usize]
            && !nonchar[cp as usize]
    };

    let prefix: Vec<u32> = ASCII_PREFIX.chars().map(|c| c as u32).collect();
    for &cp in &prefix {
        assert!(accepted(cp) && tier1(cp), "U+{cp:04X} in the ASCII prefix");
    }
    let mut first: Vec<u32> = prefix.clone();
    let mut second: Vec<u32> = Vec::new();
    for cp in 0..=MAX {
        if !accepted(cp) || prefix.contains(&cp) {
            continue;
        }
        if tier1(cp) {
            first.push(cp);
        } else {
            second.push(cp);
        }
    }

    let mut out = String::new();
    writeln!(out, "// SPDX-License-Identifier: Apache-2.0").unwrap();
    writeln!(out, "// Copyright 2026 The pixel-perfect Authors").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "//! Generated by `tools/gen-alphabet` from the Unicode {version} Character\n\
         //! Database. Do not edit by hand: see `tools/gen-alphabet/README.md`."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// Unicode version the tiers are derived from.").unwrap();
    writeln!(out, "pub const UNICODE_VERSION: &str = {version:?};").unwrap();
    writeln!(out).unwrap();
    write_tier(&mut out, "TIER1", "Tier 1 (single-column, visible)", &first);
    writeln!(out).unwrap();
    write_tier(&mut out, "TIER2", "Tier 2 (every other accepted character)", &second);
    print!("{out}");
    eprintln!(
        "tier 1: {} characters, tier 2: {} characters, total {}",
        first.len(),
        second.len(),
        first.len() + second.len()
    );
}

/// Writes code points as inclusive ranges, merging consecutive runs.
fn write_tier(out: &mut String, name: &str, doc: &str, cps: &[u32]) {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for &cp in cps {
        match ranges.last_mut() {
            Some((_, end)) if *end + 1 == cp => *end = cp,
            _ => ranges.push((cp, cp)),
        }
    }
    let total: usize = cps.len();
    writeln!(out, "/// {doc}: {total} characters as inclusive code point").unwrap();
    writeln!(out, "/// ranges, in alphabet order.").unwrap();
    writeln!(out, "pub const {name}: &[(u32, u32)] = &[").unwrap();
    for (start, end) in ranges {
        writeln!(out, "    (0x{start:04X}, 0x{end:04X}),").unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// General category of every code point; `Cn` where unlisted.
fn general_categories(text: &str) -> Vec<&str> {
    let mut gc = vec!["Cn"; MAX as usize + 1];
    let mut range_start: Option<u32> = None;
    for line in text.lines() {
        let fields: Vec<&str> = line.split(';').collect();
        let cp = u32::from_str_radix(fields[0], 16).expect("code point");
        let (name, cat) = (fields[1], fields[2]);
        if name.ends_with(", First>") {
            range_start = Some(cp);
        } else if name.ends_with(", Last>") {
            let start = range_start.take().expect("range start");
            for c in start..=cp {
                gc[c as usize] = cat;
            }
        } else {
            gc[cp as usize] = cat;
        }
    }
    gc
}

/// Parses `a..b ; value` lines (and `# @missing:` defaults, which apply first,
/// later ones overriding earlier ones) into one value per code point.
fn property_values(text: &str) -> Vec<String> {
    let mut values = vec![String::new(); MAX as usize + 1];
    let mut explicit: Vec<(u32, u32, String)> = Vec::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("# @missing:") {
            let (start, end, value) = parse_range_line(rest);
            for c in start..=end {
                values[c as usize] = value.clone();
            }
            continue;
        }
        let content = line.split('#').next().unwrap_or("").trim();
        if content.is_empty() {
            continue;
        }
        explicit.push(parse_range_line(content));
    }
    for (start, end, value) in explicit {
        for c in start..=end {
            values[c as usize] = value.clone();
        }
    }
    values
}

fn parse_range_line(line: &str) -> (u32, u32, String) {
    let mut parts = line.split(';');
    let range = parts.next().expect("range").trim();
    let value = parts.next().expect("value").trim().to_owned();
    let (start, end) = match range.split_once("..") {
        Some((a, b)) => (a, b),
        None => (range, range),
    };
    (
        u32::from_str_radix(start, 16).expect("start"),
        u32::from_str_radix(end, 16).expect("end"),
        value,
    )
}

/// Code points having the binary property `name`.
fn binary_property(text: &str, name: &str) -> Vec<bool> {
    let mut set = vec![false; MAX as usize + 1];
    let mut seen = false;
    for line in text.lines() {
        let content = line.split('#').next().unwrap_or("").trim();
        if content.is_empty() {
            continue;
        }
        let (start, end, value) = parse_range_line(content);
        if value == name {
            seen = true;
            for c in start..=end {
                set[c as usize] = true;
            }
        }
    }
    assert!(seen, "property {name} not found");
    set
}
